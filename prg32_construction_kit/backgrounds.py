"""Backgrounds: PRG32 tiles and the playfield maps made of them (docs/backgrounds.md).

A background is a project asset of kind ``background``. Its ``data`` is::

    {"width": 40, "height": 25,                       # the map, in tiles (at most 64 x 32)
     "tiles": [{"id": 1, "name": "brick", "rows": [255, 129, ...],   # 8 rows, bit 7 = leftmost pixel
                "fg": "#c84c0c", "bg": "#000000", "flags": ["solid"]}, ...],
     "layers": [[[0, 1, 1, ...], ...], ...]}         # 1 or 2 layers of tile ids (0 = empty)

That is exactly what the PRG32 draws: ``prg32_tile_define`` (an 8x8 one-bit picture in a foreground
and a background colour), ``prg32_playfield_put`` into layer 0 (behind) or 1 (in front), and
``prg32_platform_tile_flags`` for the platform helpers (prg32.h). ``to_c`` writes the arrays and a
``<name>_load()`` function that defines the tiles and fills the playfields.
"""

from __future__ import annotations

import re
from typing import Any

from .messages import text as say

MAX_COLS, MAX_ROWS, LAYERS = 64, 32, 2          # PRG32_PLAYFIELD_COLS, _ROWS, _LAYERS
FLAGS = {"solid": 1, "platform": 2, "hazard": 4, "collect": 8}   # PRG32_TILE_FLAG_*
_HEX = re.compile(r"^#[0-9a-f]{6}$")


class BackgroundError(ValueError):
    pass


def _whole(value: Any, low: int, high: int) -> bool:
    return isinstance(value, int) and not isinstance(value, bool) and low <= value <= high


def checked(data: Any) -> dict[str, Any]:
    """The background, normalised, or BackgroundError saying what is wrong."""
    if not isinstance(data, dict):
        raise BackgroundError(say("background", "A background must be an object with tiles and layers."))
    width, height = data.get("width"), data.get("height")
    if not _whole(width, 1, MAX_COLS) or not _whole(height, 1, MAX_ROWS):
        raise BackgroundError(say("background", "The map is 1 to {cols} tiles wide and 1 to {rows} tiles high.",
                                  cols=MAX_COLS, rows=MAX_ROWS))
    tiles, ids = [], set()
    if not isinstance(data.get("tiles"), list) or len(data["tiles"]) > 255:
        raise BackgroundError(say("background", "A background has a list of at most 255 tiles."))
    for tile in data["tiles"]:
        if not isinstance(tile, dict) or not _whole(tile.get("id"), 1, 255) or tile["id"] in ids:
            raise BackgroundError(say("background", "Every tile needs its own number from 1 to 255 (0 is empty)."))
        rows = tile.get("rows")
        if not isinstance(rows, list) or len(rows) != 8 or not all(_whole(row, 0, 255) for row in rows):
            raise BackgroundError(say("background", "A tile is 8 rows of 8 pixels (a number from 0 to 255 per row)."))
        colors = [str(tile.get(key, "")).lower() for key in ("fg", "bg")]
        if not all(_HEX.match(color) for color in colors):
            raise BackgroundError(say("background", "Tile colours must look like #rrggbb."))
        flags = tile.get("flags", [])
        if not isinstance(flags, list) or any(flag not in FLAGS for flag in flags):
            raise BackgroundError(say("background", "Tile flags are solid, platform, hazard and collect."))
        ids.add(tile["id"])
        tiles.append({"id": tile["id"], "name": str(tile.get("name") or f"tile {tile['id']}")[:32], "rows": list(rows),
                      "fg": colors[0], "bg": colors[1], "flags": [flag for flag in FLAGS if flag in flags]})
    layers = data.get("layers")
    if not isinstance(layers, list) or not 1 <= len(layers) <= LAYERS:
        raise BackgroundError(say("background", "A background has 1 or 2 layers."))
    for layer in layers:
        if not isinstance(layer, list) or len(layer) != height or any(
                not isinstance(row, list) or len(row) != width for row in layer):
            raise BackgroundError(say("background", "Each layer is {height} rows of {width} tiles.", height=height, width=width))
        for row in layer:
            for cell in row:
                if not (cell == 0 or (_whole(cell, 1, 255) and cell in ids)):
                    raise BackgroundError(say("background", "A map cell is 0 (empty) or the number of one of the tiles."))
    return {"width": width, "height": height, "tiles": tiles, "layers": layers}


def to_c(name: str, data: Any) -> str:
    """The tiles, flags and maps as C arrays, and ``<name>_load()`` (prg32_tile_define, prg32_playfield_put)."""
    from .generator import _rgb565, c_identifier

    background = checked(data)
    name = c_identifier(name, "background")
    tiles, width, height = background["tiles"], background["width"], background["height"]
    count = len(tiles)
    flagged = any(tile["flags"] for tile in tiles)
    lines = [f"/* Background generated by PRG32-Construction-Kit: {count} tile(s), a {width}x{height} map, "
             f"{len(background['layers'])} layer(s). Needs the tilemap feature"
             + (" and, for the tile flags, the platformer feature." if flagged else ".") + " */",
             "#include <stdint.h>", '#include "prg32.h"']
    if count:
        lines.append("/* The tiles: 8 rows of 8 pixels, the leftmost pixel in the highest bit; a 1 is drawn in the "
                     "foreground colour, a 0 in the background colour. */")
        lines.append(f"static const uint8_t {name}_tile_ids[{count}] = {{ {', '.join(str(tile['id']) for tile in tiles)} }};")
        lines.append(f"static const uint8_t {name}_tiles[{count}][8] = {{")
        for number, tile in enumerate(tiles):
            lines.append("    { " + ", ".join(f"0x{row:02X}" for row in tile["rows"]) + " }"
                         + ("," if number < count - 1 else "") + f"  /* {tile['id']}: {tile['name']} */")
        lines += ["};", "/* Foreground and background of each tile, RGB565. */",
                  f"static const uint16_t {name}_tile_colors[{count}][2] = {{"]
        for number, tile in enumerate(tiles):
            lines.append(f"    {{ 0x{_rgb565(tile['fg']):04X}, 0x{_rgb565(tile['bg']):04X} }}"
                         + ("," if number < count - 1 else "") + f"  /* {tile['fg']} on {tile['bg']} */")
        lines.append("};")
        if flagged:
            lines.append("/* What each tile is for the platform helpers (PRG32_TILE_FLAG_*: 1 solid, 2 platform, "
                         "4 hazard, 8 collect). */")
            lines.append(f"static const uint8_t {name}_tile_flags[{count}] = {{ "
                         + ", ".join(str(sum(FLAGS[flag] for flag in tile["flags"])) for tile in tiles) + " };")
    for number, layer in enumerate(background["layers"]):
        lines.append(f"/* Layer {number} ({'behind' if number == 0 else 'in front'}): one tile number per cell, 0 is empty. */")
        lines.append(f"static const uint8_t {name}_layer{number}[{height}][{width}] = {{")
        for y, row in enumerate(layer):
            lines.append("    { " + ", ".join(str(cell) for cell in row) + " }" + ("," if y < height - 1 else ""))
        lines.append("};")
    lines += ["/* Call it once (in init): it defines the tiles and fills the playfield layers. Each frame, draw them",
              "   with prg32_playfield_draw(0, 0); prg32_playfield_draw(1, 1); (1: tile 0 shows what is behind). */",
              f"void {name}_load(void) {{"]
    if count:
        lines += [f"    for (int i = 0; i < {count}; i++) {{",
                  f"        prg32_tile_define({name}_tile_ids[i], {name}_tiles[i], {name}_tile_colors[i][0], {name}_tile_colors[i][1]);"]
        if flagged:
            lines.append(f"        prg32_platform_tile_flags({name}_tile_ids[i], {name}_tile_flags[i]);")
        lines.append("    }")
    for number in range(len(background["layers"])):
        lines += [f"    prg32_playfield_clear({number}, 0);",
                  f"    for (int y = 0; y < {height}; y++) {{",
                  f"        for (int x = 0; x < {width}; x++) {{",
                  f"            prg32_playfield_put({number}, (uint8_t)x, (uint8_t)y, {name}_layer{number}[y][x]);",
                  "        }", "    }"]
    lines += ["}", ""]
    return "\n".join(lines)
