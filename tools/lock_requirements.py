"""Pin the kit's Python packages with hashes (docs/dependencies.md).

    python3 tools/lock_requirements.py           # resolve and write requirements.lock (needs PyPI)
    python3 tools/lock_requirements.py --check   # offline: does the lock still fit the requirements?

requirements-production.txt (which includes requirements.txt) says which packages and
which versions are acceptable. requirements.lock says exactly which ones the Docker
image installs, with the SHA-256 of every file PyPI has for that version, so
``pip install --require-hashes -r requirements.lock`` refuses anything else. The
resolution is done for the image: Linux, CPython 3.12, wheels only.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements-production.txt"
LOCK = ROOT / "requirements.lock"
PLATFORMS = ("manylinux_2_17_x86_64", "manylinux_2_17_aarch64", "manylinux2014_x86_64", "manylinux2014_aarch64",
             "manylinux_2_28_x86_64", "manylinux_2_28_aarch64")


def requirement_lines(path: Path) -> list[str]:
    """Requirement lines, following -r includes."""
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("-r "):
            lines += requirement_lines(path.parent / line[3:].strip())
        else:
            lines.append(line)
    return lines


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def resolve() -> dict[str, str]:
    """name -> version, as pip resolves the requirements for the image."""
    with tempfile.TemporaryDirectory() as folder:
        report = Path(folder) / "report.json"
        command = [sys.executable, "-m", "pip", "install", "--quiet", "--dry-run", "--ignore-installed",
                   "--only-binary=:all:", "--python-version", "3.12", "--implementation", "cp", "--target", folder,
                   "--report", str(report), "-r", str(REQUIREMENTS)]
        for platform in PLATFORMS:
            command += ["--platform", platform]
        subprocess.run(command, check=True)
        installed = json.loads(report.read_text())["install"]
    return {canonical(item["metadata"]["name"]): item["metadata"]["version"] for item in installed}


def hashes(name: str, version: str) -> list[str]:
    import requests   # a kit dependency, with its own CA bundle

    answer = requests.get(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30)
    answer.raise_for_status()
    files = answer.json()["urls"]
    return sorted({item["digests"]["sha256"] for item in files})


def write() -> None:
    pinned = resolve()
    lines = ["# Generated by tools/lock_requirements.py from requirements-production.txt. Do not edit by hand.",
             "# Linux, CPython 3.12. Install with: pip install --require-hashes -r requirements.lock", ""]
    for name in sorted(pinned):
        digests = hashes(name, pinned[name])
        lines.append(f"{name}=={pinned[name]} \\")
        lines += [f"    --hash=sha256:{digest}" + (" \\" if index < len(digests) - 1 else "")
                  for index, digest in enumerate(digests)]
    LOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {LOCK.relative_to(ROOT)} ({len(pinned)} packages)")


def locked() -> dict[str, str]:
    return {canonical(match.group(1)): match.group(2)
            for match in re.finditer(r"^([A-Za-z0-9_.\-]+)==([^\s\\]+)", LOCK.read_text(encoding="utf-8"), re.M)}


def check() -> int:
    from packaging.requirements import Requirement

    if not LOCK.is_file():
        print("requirements.lock is missing (run python3 tools/lock_requirements.py)", file=sys.stderr)
        return 1
    pins = locked()
    problems = []
    for line in requirement_lines(REQUIREMENTS):
        requirement = Requirement(line)
        name = canonical(requirement.name)
        if name not in pins:
            problems.append(f"{name} is not in the lock")
        elif not requirement.specifier.contains(pins[name], prereleases=True):
            problems.append(f"{name}=={pins[name]} does not satisfy {requirement.specifier}")
    text = LOCK.read_text(encoding="utf-8")
    for name in pins:
        if not re.search(rf"^{re.escape(name)}==\S+ \\\n\s+--hash=sha256:[0-9a-f]{{64}}", text, re.M | re.I):
            problems.append(f"{name} has no hash")
    if problems:
        print("requirements.lock is out of date: " + "; ".join(problems) + " (run python3 tools/lock_requirements.py)",
              file=sys.stderr)
        return 1
    print(f"requirements.lock fits the requirements ({len(pins)} packages, all with hashes)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check()
    write()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
