"""Write the browser copies of the interface catalogs (ADR-0027).

    python3 tools/build_i18n.py            # static/i18n/<locale>.json -> static/i18n/<locale>.js
    python3 tools/build_i18n.py --check    # fail if a .js copy is out of date

The .json catalogs are the source (the server reads them); the .js copies let pages, and the
static offline pages, load a catalog with a plain script tag under the strict Content Security
Policy (no inline scripts, no fetch before the page starts).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from prg32_construction_kit.i18n import CATALOG_DIR, LOCALES  # noqa: E402


def render(locale: str) -> str:
    data = json.loads((CATALOG_DIR / f"{locale}.json").read_text(encoding="utf-8"))
    messages = {key: value for key, value in sorted(data.items()) if not key.startswith("_")}
    body = json.dumps(messages, indent=0, sort_keys=True, ensure_ascii=True)
    return ("// Generated by tools/build_i18n.py from static/i18n/" + locale + ".json. Do not edit.\n"
            "(window.PRG32I18nCatalogs = window.PRG32I18nCatalogs || {})['" + locale + "'] = " + body + ";\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for locale in LOCALES:
        path = CATALOG_DIR / f"{locale}.js"
        text = render(locale)
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("Out of date (run python3 tools/build_i18n.py): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print("Catalogs up to date" if args.check else f"Wrote {len(LOCALES)} catalogs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
