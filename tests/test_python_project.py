@pytest.mark.parametrize("language", ["c", "asm"])
def test_source_maps_lead_from_generated_lines_back_to_python(language):
    source = EXAMPLE.read_text()
    project = {"title": "Brick Catch", "game_json": {"source_mode": "python", "source_python": source}}
    game_ir, text, source_map = project_source_map(project, language)
    plain = ir_to_c(game_ir) if language == "c" else ir_to_asm(game_ir)
    assert text == plain                                    # the markers changed nothing
    assert source_map["python_file"] == "game.py" and len(source_map["python_sha256"]) == 64
    lines = source.splitlines()
    assert source_map["entries"]
    for entry in source_map["entries"]:
        line, column, end_line, _end_column = entry["python"]
        assert entry["block"] == "py:" + ":".join(map(str, entry["python"]))
        assert 1 <= line <= end_line <= len(lines) and column >= 1
        first, last = entry["lines"]
        assert 1 <= first <= last <= len(plain.splitlines())
    rect = next(entry for entry in source_map["entries"] if entry["op"] == "rect")
    assert "prg32.rect(" in lines[rect["python"][0] - 1]


