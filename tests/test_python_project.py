def game(init: str = "pass", update: str = "pass", draw: str = "pass", top: str = "") -> str:
    """A whole game.py with the three lifecycle functions (each body one line or an indented block)."""
    return (f"import prg32\nx: int = 0\nflag: bool = False\nitems: list[int] = [0] * 4\n{top}\n"
            f"def init() -> None:\n    {init}\n\ndef update() -> None:\n    {update}\n\ndef draw() -> None:\n    {draw}\n")


def ir_of(source: str, **project) -> dict:
    return pp.python_to_ir(source, {"title": "Py Test", **project})


def refusal(source: str) -> pp.PythonError:
    with pytest.raises(pp.PythonError) as caught:
        ir_of(source)
    return caught.value


