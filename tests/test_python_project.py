def test_the_starter_becomes_the_same_ir_contract_as_the_blocks():
    ir = ir_of(pp.STARTER)
    events = [{"type": kind} for kind in ("prg32_on_start", "prg32_update", "prg32_draw")]
    blocks = blocks_to_ir({"blocks": {"blocks": events}}, {"title": "Py Test"})
    # One IR contract (generator.IR_ABI): Python adds only its source mode and language version.
    assert ir["abi"] == blocks["abi"] and set(blocks) <= set(ir)
    assert set(ir) - set(blocks) == {"source_mode", "python_language_version"}
    assert ir["source_mode"] == "python" and ir["python_language_version"] == pp.LANGUAGE_VERSION
    assert [item["name"] for item in ir["state"]] == ["player_x", "player_y", "score"]
    c, asm = ir_to_c(ir), ir_to_asm(ir)
    for phase in ("init", "update", "draw"):
        assert f"void py_test_{phase}(void)" in c and f"py_test_{phase}:" in asm


def test_generated_c_and_assembly_explain_every_python_step():
    c, asm = ir_to_c(ir_of(pp.STARTER)), ir_to_asm(ir_of(pp.STARTER))
    assert "Generated by PRG32-Construction-Kit from the saved PRG32 Python (game.py)." in c
    assert "from the saved PRG32 Python." in asm
    # Each statement is headed by its sentence; no "Block" wording in a Python project's files.
    assert 'Step "change player_x by -3"' in c and 'Step "change player_x by -3"' in asm
    assert 'Block "' not in c and 'Block "' not in asm
    assert "Runs every frame: read the buttons, move things." in c   # docstrings stay as comments


def test_builds_are_deterministic_in_fresh_processes():
    """The same game.py gives byte-identical IR, C and assembly in clean processes (other hash seeds)."""
    script = ("import json, sys; from prg32_construction_kit import python_project as pp;"
              "from prg32_construction_kit.generator import ir_to_c;"
              "from prg32_construction_kit.asm_generator import ir_to_asm;"
              "ir = pp.python_to_ir(sys.stdin.read(), {'title': 'Py Test'});"
              "print(json.dumps([ir, ir_to_c(ir), ir_to_asm(ir)], sort_keys=True))")
    source = EXAMPLE.read_text()
    outputs = {subprocess.run([sys.executable, "-c", script], input=source, capture_output=True, text=True, check=True,
                              cwd=ROOT, env={**os.environ, "PYTHONHASHSEED": seed, "LC_ALL": locale_name}).stdout
               for seed, locale_name in (("0", "C"), ("1", "C"), ("4242", "en_US.UTF-8"))}
    assert len(outputs) == 1
    ir = ir_of(source)
    assert json.loads(outputs.pop()) == [ir, ir_to_c(ir), ir_to_asm(ir)]


def test_the_example_game_uses_every_kind_of_statement():
    ir = ir_of(EXAMPLE.read_text())
    ops: set[str] = set()

    def walk(statements):
        for stmt in statements:
            ops.add(stmt["op"])
            for key in ("then", "else", "body"):
                walk(stmt.get(key, []))
    for phase in ("init", "update", "draw"):
        walk(ir[phase])
    assert {"set", "change", "if", "repeat", "list_set", "list_change", "if_button", "if_button_once",
            "if_touching", "clear", "rect", "text", "number", "note", "comment"} <= ops
    assert {"audio", "sprites"} <= set(ir["required_features"])


