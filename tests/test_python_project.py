@pytest.mark.parametrize("a,b", [(7, 2), (-7, 2), (7, -2), (-7, -2), (5, 0), (-5, 0), (0, 3)])
def test_whole_number_division_rounds_toward_zero_like_the_cpu(a, b):
    """// and % follow C and RISC-V (documented in docs/python_language.md), not desktop Python."""
    q, r = pp._c_div(a, b), pp._c_mod(a, b)
    if b == 0:
        assert (q, r) == (-1, a)
    else:
        assert q == int(a / b) and q * b + r == a
    assert ir_of(game(top=f"q: int = ({a}) // ({b})\nr: int = ({a}) % ({b})"))["state"][2:4] == [
        {"name": "q", "type": "int", "initial": q}, {"name": "r", "type": "int", "initial": r}]


def test_starting_values_wrap_at_32_bits():
    ir = ir_of(game(top="big: int = 2147483647 + 1\nshift: int = 1 << 31"))
    assert ir["state"][2]["initial"] == -2147483648 == ir["state"][3]["initial"]


def test_python_precedence_is_kept_in_the_c_syntax():
    """Python: a & b == c is (a & b) == c; C would read it as a & (b == c)."""
    ir = ir_of(game(update="global flag\n    flag = x & 3 == 1 and not flag or x > 2"))
    # && binds tighter than || in C, as 'and' binds tighter than 'or' in Python: no brackets needed.
    assert ir["update"][0]["value"] == "(x & 3) == 1 && !flag || x > 2"


def test_if_elif_else_and_loops_become_nested_ir():
    source = game(update="global x\n    for i in range(2, 5):\n        if i == 3:\n            x += i\n"
                         "        elif i > 3:\n            x -= 1\n        else:\n            x = x * 2")
    loop = ir_of(source)["update"][0]
    assert loop["op"] == "repeat" and (loop["from"], loop["to"], loop["var"]) == ("2", "4", "update_i")
    branch = loop["body"][0]
    assert branch["cond"] == "update_i == 3" and branch["then"] == [{"op": "change", "var": "x", "delta": "update_i"}]
    assert branch["else"][0]["cond"] == "update_i > 3"
    assert branch["else"][0]["else"] == [{"op": "set", "var": "x", "value": "x * 2"}]


def test_button_tests_join_other_conditions_as_nested_ifs():
    source = game(update="global x\n    if x > 0 and prg32.pressed(prg32.A) and flag:\n        x = 0")
    outer = ir_of(source)["update"][0]
    assert outer == {"op": "if", "cond": "x > 0", "then": [
        {"op": "if_button_once", "button": "A", "then": [{"op": "if", "cond": "flag", "then": [
            {"op": "set", "var": "x", "value": "0"}]}]}]}


def test_helper_functions_are_copied_in_with_their_parameters():
    source = game(top="def add(n: int) -> None:\n    global x\n    left: int = x\n    x = left + n\n\n"
                      "def twice(v: int) -> int:\n    return v * 2\n",
                  update="add(twice(3) + 1)\n    add(1)")
    ir = ir_of(source)
    names = [item["name"] for item in ir["state"]]
    assert "add_n" in names and "add_left" in names       # one variable for every copy
    update = ir["update"]
    assert update[1] == {"op": "set", "var": "add_n", "value": "(3 * 2) + 1"}
    assert [stmt["op"] for stmt in update] == ["comment", "set", "set", "set", "comment", "set", "set", "set"]


def test_lists_start_with_their_values_before_init():
    ir = ir_of(game(top="levels: list[int] = [3, 0, 7]\nfull: list[int] = [9] * 5"))
    assert {"name": "levels", "size": 3} in ir["lists"] and {"name": "full", "size": 5} in ir["lists"]
    assert ir["init"][:3] == [{"op": "list_set", "list": "levels", "index": "0", "value": "3"},
                              {"op": "list_set", "list": "levels", "index": "2", "value": "7"},
                              {"op": "list_fill", "list": "full", "value": "9"}]


def test_sound_names_become_fixed_numbers_from_audiostudio():
    document = {"effects": [{"name": "boom", "voice": 3, "note": 60, "volume": 200, "duration_ms": 120}],
                "soundtracks": [{"name": "theme"}]}
    effect, track = "boom", "theme"
    ir = ir_of(game(init=f"prg32.sound_effect({effect!r})\n    prg32.soundtrack_play({track!r})"),
               audio_studio=document)
    assert ir["init"][0]["op"] == "sfx" and ir["init"][0]["instrument"] == 8
    assert ir["init"][1] == {"op": "track_play", "name": track, "track": 0}
    assert refusal(game(init="prg32.sound_effect('nope')")).code == "missing_sound"


