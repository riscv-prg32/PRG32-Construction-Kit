# --- the projects API -----------------------------------------------------------------------------

def python_game_json(source: str = pp.STARTER) -> dict:
    return {"source_mode": "python", "source_python": source, "python_language_version": pp.LANGUAGE_VERSION}


def make_project(client, source: str = pp.STARTER, title: str = "Py Game") -> dict:
    response = client.post("/api/projects", json={"title": title, "game_json": python_game_json(source)})
    assert response.status_code == 201, response.get_json()
    return response.get_json()


def test_a_python_project_saves_converts_and_keeps_its_type(client):
    project = make_project(client)
    pid = project["id"]
    answer = client.post(f"/api/projects/{pid}/convert", json={"source_language": "both"}).get_json()
    assert answer["game_ir"]["source_mode"] == "python" and "void py_game_draw(void)" in answer["c_source"]
    assert {artifact["kind"] for artifact in answer["artifacts"]} == {"c_source", "asm_source"}
    # The type is fixed: no save turns it into Blocks or C, and Blocks cannot become Python.
    for other in ({}, {"source_mode": "c", "source_c": "int x;"}):
        refused = client.put(f"/api/projects/{pid}", json={"game_json": other, "expected_version": project["version"]})
        assert refused.status_code == 409 and refused.get_json()["code"] == "type_locked"
    blocks = client.post("/api/projects", json={"title": "B", "blocks_json": {}}).get_json()
    refused = client.put(f"/api/projects/{blocks['id']}", json={"game_json": python_game_json(),
                                                                "expected_version": blocks["version"]})
    assert refused.status_code == 409 and refused.get_json()["project_type"] == "blocks"
    assert client.post(f"/api/projects/{pid}/convert_to", json={"language": "c"}).status_code == 409


