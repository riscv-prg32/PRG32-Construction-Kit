def test_package_puts_game_py_in_the_bundle_and_records_provenance(client, monkeypatch):
    from types import SimpleNamespace

    def fake_builder(command, **_kwargs):
        Path(command[command.index("--out") + 1]).write_bytes(b"PRG2" + bytes(60))
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    monkeypatch.setattr("prg32_construction_kit.packager.subprocess.run", fake_builder)
    monkeypatch.setattr("prg32_construction_kit.routes.toolchain_present", lambda _command: True)
    project = make_project(client)
    body = client.post(f"/api/projects/{project['id']}/package", json={"source_language": "both"}).get_json()
    import io
    import zipfile

    bundle = client.get(f"/api/artifacts/{body['bundle_artifact']['id']}/download").data
    with zipfile.ZipFile(io.BytesIO(bundle)) as archive:
        names = set(archive.namelist())
        assert {"source/game.py", "source/game.c", "source/game.S", "source/game.ir.json"} <= names
        assert archive.read("source/game.py").decode() == pp.STARTER
    provenance = body["build"]["metadata"]["provenance"]
    assert provenance["authoring"] == "python"
    assert provenance["python"]["language"] == pp.LANGUAGE and provenance["python"]["grammar"] == pp.GRAMMAR
    from prg32_construction_kit.provenance import ir_fingerprint, sha256_text
    assert provenance["python"]["source_sha256"] == sha256_text(pp.STARTER)
    assert provenance["python"]["ir_sha256"] == ir_fingerprint(ir_of(pp.STARTER, title="Py Game"))


